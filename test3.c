#include <stdio.h>

int main() {
    // 整数格式化
    printf("|%5d|\n", 42);        // 总宽5，右对齐
    printf("|%-5d|\n", 42);       // 总宽5，左对齐
    printf("|%05d|\n", 42);       // 总宽5，前导0填充
    printf("|%+d|\n", 42);        // 显示正号
    
    // 浮点数格式化
    printf("|%8.2f|\n", 3.14159); // 总宽8，小数2位
    printf("|%-8.2f|\n", 3.14159);// 左对齐
    printf("|%.3f|\n", 3.14159);  // 小数3位，宽度自动
    
    // 字符串格式化
    printf("|%10s|\n", "cat");    // 总宽10，右对齐
    printf("|%-10s|\n", "cat");   // 总宽10，左对齐
    printf("|%.3s|\n", "Hello");  // 只输出前3个字符
    
    // 其他
    printf("百分号：%%\n");
    printf("科学计数法：%e\n", 12345.678);
    printf("十六进制：%x\n", 255);
    printf("八进制：%o\n", 255);

    int a = 42;
    int b = -42;
    // + 这个标志的作用是“强制显示符号”。对于正数，它在前面加 +；对于负数，它什么都不做（负数原本就会显示 -）。
    printf("%d\n", a);    // 输出 42
    printf("%+d\n", a);   // 输出 +42
    printf("%d\n", b);    // 输出 -42
    printf("%+d\n", b);   // 输出 -42 （依然是负号，不会变成 "+-42"）

    printf("|%.3s|\n", "Hello");  // |Hel| （精度截断）
    printf("|%3s|\n", "Hello");   // |Hello| （宽度不够，不截断）
    printf("|%8s|\n", "Hello");   // |   Hello| （宽度8，补3个空格）
    printf("|%8.3s|\n", "Hello"); // |     Hel| （宽度8，精度截断成3，补5个空格）
    // %.3s（带点）：.3 是精度，表示“最多只输出3个字符”，所以 Hello 被截断成了 Hel。
    // %3s（不带点）：3 是最小字段宽度，表示“至少占3个位置”。因为 Hello 有5个字符，超过3个，所以它会完整输出 Hello，根本不会截断。如果输出的是 "Hi"（2个字符），它会在前面补一个空格变成 " Hi"。
    // %s（什么都不加）：原样输出 Hello。
    // 带 . 是限制字符个数（截断），不带 . 是限制输出宽度（补空格）
    
    return 0;
}