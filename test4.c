#include <stdio.h>

int main() {
    int age;
    char ch;
    
    printf("请输入年龄：");
    scanf("%d", &age);        // 输入 "25\n"，换行符留在缓冲区
    
    // 必须清除缓冲区中的换行符，否则下一句会读到 '\n'
    // getchar()：从输入缓冲区读取一个字符。
    // != '\n'：判断读到的这个字符是不是回车换行符。
    // while (...) ;：循环条件。如果条件为真（读到的不是换行符），就重复执行循环体（这里的循环体是空的，也就是一个分号 ;）。
    // 即：不断从缓冲区读取字符并丢弃，直到读完回车换行符为止。
    // while (getchar() != '\n');  
    int c;
    while ((c = getchar()) != '\n' && c != EOF); // 更严谨，防死循环
    // 虽然 while (getchar() != '\n'); 可以清空缓冲区，但在极特殊情况下（比如输入流结束或者发生错误），getchar() 会返回 EOF（通常是 -1）。如果一直返回 EOF，条件永远为真，会导致死循环。

    printf("请输入一个字符：");
    scanf("%c", &ch);         // 现在可以正确读取字符了
    //scanf(" %c", &ch);        // " %c"：scanf 会自动跳过缓冲区中所有的空白字符，直到遇到第一个可见字符才读取。
    
    printf("年龄：%d，字符：%c\n", age, ch);
    return 0;
}